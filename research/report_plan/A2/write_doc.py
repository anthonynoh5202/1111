def p05_list():
    hits = []
    tests = 0
    for lv, res in R.items():
        for k, c in res["combos"].items():
            for per in ("IS", "OOS"):
                m = c.get(per, {})
                if m.get("p_vs_rand") is not None:
                    tests += 1
                    if m["p_vs_rand"] < 0.05:
                        other = c.get("OOS" if per == "IS" else "IS", {})
                        hits.append(f"{lv} {k} {per}: {m['n']}건 {f(m['exp'], 2, True)}R (p={m['p_vs_rand']:.3f}) "
                                    f"→ 반대 기간 {other.get('n', 0)}건 {f(other.get('exp', float('nan')), 2, True)}R")
    return tests, hits


